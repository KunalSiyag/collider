parts.push(block(58, 12, 4, '#4ade80'));
parts.push(block(56, 10, 24, '#22d3ee'));
let truck = box(64, 30, 8, 34, 20, 14, '#ef4444') + box(96, 30, 8, 14, 20, 20, accent);
